export function getAllThemes(): ThemePage[] {
  return themes.map((t) => ({
    id: t.id,
    label: t.label,
    icon: t.icon,
    sentences: t.sentences.map((s, i) => ({
      id: `${t.id}-s${i + 1}`,
      german: s.german,
      english: s.english,
      phonetic: s.phonetic,
      theme: t.id,
      themeLabel: t.label,
    })),
  }))
}

// Cache for custom sentences from Dexie
let customSentencesCache: Array<{
  id: string
  german: string
  english: string
  phonetic: string
  theme: string
}> = []

export function setCustomSentencesForMerge(data: typeof customSentencesCache): void {
  customSentencesCache = data
}

export function getAllSentences(): Sentence[] {
  const base = getAllThemes().flatMap((t) => t.sentences)

  // Merge in custom user-created sentences from Dexie cache
  for (const c of customSentencesCache) {
    base.push({
      id: c.id,
      german: c.german,
      english: c.english,
      phonetic: c.phonetic || "",
      theme: c.theme || "custom",
      themeLabel: "Custom",
    })
  }

  return base
}

export function getThemeById(id: string): ThemePage | undefined {
  return getAllThemes().find((t) => t.id === id)
}
